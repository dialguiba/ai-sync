func runSetup(workdir string, config setupConfig, dryRun bool) ([]string, error) {
	var changes []string
	var errs []error
	for _, name := range sortedStringMapKeys(config) {
		entry := config[name]

		check := exec.Command("sh", "-c", entry.Check)
		check.Dir = workdir
		if err := check.Run(); err == nil {
			changes = append(changes, "ok "+name)
			continue
		}

		if dryRun {
			changes = append(changes, "would install "+name)
			continue
		}

		install := exec.Command("sh", "-c", entry.Install)
		install.Dir = workdir
		output, err := install.CombinedOutput()
		if err != nil {
			errs = append(errs, fmt.Errorf("setup %s: %w\n%s", name, err, strings.TrimSpace(string(output))))
			changes = append(changes, "failed "+name)
			continue
		}
		changes = append(changes, "installed "+name)
	}
	return changes, errors.Join(errs...)
}

func loadSkills(root string) ([]skill, error) {
	entries, err := os.ReadDir(root)
	if err != nil {
		if os.IsNotExist(err) {
			return nil, nil
		}
		return nil, fmt.Errorf("read .ai/skills: %w", err)
	}

	var skills []skill
	for _, entry := range entries {
		if !entry.IsDir() || strings.HasPrefix(entry.Name(), ".") {
			continue
		}
		name := entry.Name()
		files := map[string][]byte{}
		skillRoot := filepath.Join(root, name)
		if err := filepath.WalkDir(skillRoot, func(path string, d fs.DirEntry, err error) error {
			if err != nil {
				return err
			}
			if d.IsDir() {
				return nil
			}
			rel, err := filepath.Rel(skillRoot, path)
			if err != nil {
				return err
			}
			contents, err := os.ReadFile(path)
			if err != nil {
				return err
			}
			files[filepath.ToSlash(rel)] = contents
			return nil
		}); err != nil {
			return nil, fmt.Errorf("read skill %s: %w", name, err)
		}
		skills = append(skills, skill{Name: name, Files: files})
	}
	sort.Slice(skills, func(i, j int) bool { return skills[i].Name < skills[j].Name })
	return skills, nil
}

